export const fabricationStations = exhibits.map(
  ([title, ar, component, componentAr, note, noteAr, focus], i) => {
    const group = groups[i < 6 ? 0 : i < 8 ? 1 : 2];
    return {
      title,
      ar,
      component,
      componentAr,
      note,
      noteAr,
      focus,
      category: group[1],
      categoryAr: group[2],
      number: i + 1,
      ...exhibitBay(4, i),
    };
  },
);
export const fabricationScope = groups.map(([id, title, ar, image]) => {
  const stations = fabricationStations.filter((s) => s.category === title);
  return {
    id,
    title,
    ar,
    image,
    start: stations[0].number,
    items: stations.map((s) => [s.title, s.ar] as const),
  };
});
