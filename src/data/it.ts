export const itStations = exhibits.map(
  ([title, ar, component, componentAr, note, noteAr, focus], i) => {
    const group = groups[i < 4 ? 0 : i < 9 ? 1 : i < 14 ? 2 : 3];
    return {
      title,
      ar,
      component,
      componentAr,
      note,
      noteAr,
      focus,
      category: group[1],
      categoryAr: group[2],
      number: i + 1,
      ...exhibitBay(7, i),
    };
  },
);
export const itScope = groups.map(([id, title, ar, image]) => {
  const stations = itStations.filter((s) => s.category === title);
  return {
    id,
    title,
    ar,
    image,
    start: stations[0].number,
    items: stations.map((s) => [s.title, s.ar] as const),
  };
});
