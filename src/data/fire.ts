export const fireStations = exhibits.map(
  ([title, ar, component, componentAr, note, noteAr, focus], i) => {
    const group = groups[i < 8 ? 0 : i < 13 ? 1 : i < 15 ? 2 : 3];
    return {
      title,
      ar,
      component,
      componentAr,
      note,
      noteAr,
      focus,
      category: group[1],
      categoryAr: group[2],
      number: i + 1,
      ...exhibitBay(6, i),
    };
  },
);
export const fireScope = groups.map(([id, title, ar, image]) => {
  const stations = fireStations.filter((s) => s.category === title);
  return {
    id,
    title,
    ar,
    image,
    start: stations[0].number,
    items: stations.map((s) => [s.title, s.ar] as const),
  };
});
